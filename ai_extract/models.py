from django.contrib.postgres.indexes import GinIndex
from django.db import models

class ContractSummary(models.Model):
    """
    Executive summary generated by Kaggle Qwen AI for a contract version.
    Maps to: POST /api/v1/summarize on kaggle_qwen_service.
    """
    version = models.OneToOneField(
        "contracts.ContractVersion",
        on_delete=models.CASCADE,
        related_name="ai_summary",
        verbose_name="Contract Version",
    )
    summary = models.TextField(verbose_name="AI-Generated Summary")
    model_id = models.CharField(
        max_length=200,
        default="phamthanhfd/contract-analysis-qwen2.5-3b",
        verbose_name="Model ID",
    )
    created_at = models.DateTimeField(auto_now_add=True, verbose_name="Generated At")
    updated_at = models.DateTimeField(auto_now=True, verbose_name="Updated At")

    class Meta:
        verbose_name = "Contract Summary"
        verbose_name_plural = "Contract Summaries"

    def __str__(self):
        return f"Summary – {self.version.contract.contract_code} v{self.version.version_number}"

    @property
    def contract(self):
        return self.version.contract


class Clause(models.Model):
    version = models.ForeignKey(
        "contracts.ContractVersion", 
        on_delete=models.CASCADE, 
        related_name='ai_extract_clauses', 
        verbose_name="Contract Version"
    )
    context = models.ForeignKey(
        "contracts.ContractContext", 
        on_delete=models.SET_NULL, 
        null=True, 
        blank=True, 
        related_name='ai_extract_clauses', 
        verbose_name="Contract Context"
    )
    clause_type = models.CharField(max_length=100, blank=True, null=True, verbose_name="Clause Type")
    clause_title = models.CharField(max_length=255, verbose_name="Clause Title")
    clause_content = models.TextField(verbose_name="Clause Content")

    class Meta:
        verbose_name = 'Clause'
        verbose_name_plural = 'Clauses'

    def __str__(self):
        return f"{self.clause_title} (v{self.version.version_number})"

    @property
    def contract(self):
        return self.version.contract


class ExtractedEntity(models.Model):
    clause = models.ForeignKey(
        Clause, 
        on_delete=models.CASCADE, 
        related_name='ai_extract_entities', 
        verbose_name="Clause"
    )
    entity_type = models.CharField(max_length=100, verbose_name="Entity Type")
    entity_value = models.TextField(verbose_name="Entity Value")
    normalized_value = models.TextField(blank=True, null=True, verbose_name="Normalized Value")
    confidence_score = models.DecimalField(max_digits=5, decimal_places=2, default=0.0, verbose_name="Confidence Score")

    class Meta:
        verbose_name = 'Extracted Entity'
        verbose_name_plural = 'Extracted Entities'

    def __str__(self):
        return f"{self.entity_type}: {self.entity_value[:30]}"


class LayoutExtractionRun(models.Model):
    STATUS_CHOICES = (
        ("RUNNING", "Running"),
        ("COMPLETED", "Completed"),
        ("FAILED", "Failed"),
    )
    INDEX_STATUS_CHOICES = (
        ("PENDING", "Pending"),
        ("RUNNING", "Running"),
        ("COMPLETED", "Completed"),
        ("PARTIAL", "Partial"),
        ("FAILED", "Failed"),
        ("SKIPPED", "Skipped"),
    )
    version = models.ForeignKey(
        "contracts.ContractVersion",
        on_delete=models.CASCADE,
        related_name="layout_extraction_runs",
    )
    pipeline_name = models.CharField(max_length=100, default="plan-a-surya-colpali")
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default="RUNNING")
    total_pages = models.PositiveIntegerField(default=0)
    total_blocks = models.PositiveIntegerField(default=0)
    structure = models.JSONField(default=dict, blank=True)
    dense_index_status = models.CharField(
        max_length=20, choices=INDEX_STATUS_CHOICES, default="PENDING"
    )
    dense_points_count = models.PositiveIntegerField(default=0)
    dense_index_error = models.TextField(blank=True)
    colpali_index_status = models.CharField(
        max_length=20, choices=INDEX_STATUS_CHOICES, default="PENDING"
    )
    colpali_points_count = models.PositiveIntegerField(default=0)
    colpali_index_error = models.TextField(blank=True)
    error_message = models.TextField(blank=True)
    started_at = models.DateTimeField(auto_now_add=True)
    completed_at = models.DateTimeField(blank=True, null=True)

    class Meta:
        ordering = ["-started_at"]

    def __str__(self):
        return f"{self.version} - {self.pipeline_name} ({self.status})"


class RetrievalSnapshot(models.Model):
    """Rebuildable A2 index, never the authoritative source or access policy."""
    version = models.OneToOneField('contracts.ContractVersion', on_delete=models.CASCADE, related_name='retrieval_snapshot')
    run = models.ForeignKey(LayoutExtractionRun, null=True, on_delete=models.SET_NULL)
    dirty = models.BooleanField(default=True)
    schema = models.PositiveIntegerField(default=1)
    metadata_key = models.TextField(default='')
    records = models.JSONField(default=list)
    tree = models.JSONField(default=dict)
    graph_scope = models.JSONField(default=dict)
    passage_count = models.PositiveIntegerField(default=0)
    token_count = models.PositiveIntegerField(default=0)
    updated_at = models.DateTimeField(auto_now=True)


class RetrievalPassage(models.Model):
    snapshot = models.ForeignKey(RetrievalSnapshot, on_delete=models.CASCADE, related_name='passages')
    record = models.JSONField(default=dict)
    token_counts = models.JSONField(default=dict)
    length = models.PositiveIntegerField(default=0)

    class Meta:
        indexes = [GinIndex(fields=["token_counts"], name="retrieval_token_gin")]


class LayoutExtractionPage(models.Model):
    run = models.ForeignKey(LayoutExtractionRun, on_delete=models.CASCADE, related_name="pages")
    page_number = models.PositiveIntegerField()
    width = models.PositiveIntegerField(default=0)
    height = models.PositiveIntegerField(default=0)
    image_path = models.CharField(max_length=500, blank=True)
    extracted_text = models.TextField(blank=True)

    class Meta:
        ordering = ["page_number"]
        constraints = [
            models.UniqueConstraint(fields=["run", "page_number"], name="unique_layout_page_per_run")
        ]

    def __str__(self):
        return f"{self.run.version} - page {self.page_number}"


class LayoutExtractionBlock(models.Model):
    page = models.ForeignKey(LayoutExtractionPage, on_delete=models.CASCADE, related_name="blocks")
    block_order = models.PositiveIntegerField()
    layout_type = models.CharField(max_length=50, default="paragraph")
    text = models.TextField(blank=True)
    bbox = models.JSONField(default=list)
    structure_metadata = models.JSONField(default=dict, blank=True)
    confidence = models.DecimalField(max_digits=5, decimal_places=4, default=0)

    class Meta:
        ordering = ["block_order"]
        constraints = [
            models.UniqueConstraint(fields=["page", "block_order"], name="unique_layout_block_order")
        ]

    def __str__(self):
        return f"Page {self.page.page_number} block {self.block_order}"
