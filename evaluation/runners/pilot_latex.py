"""Write paper/results_tables.tex from a pilot report directory (summary.csv), or TBD placeholders.

  python -X utf8 -m evaluation.runners.pilot_latex REPORT_DIR paper/results_tables.tex
  python -X utf8 -m evaluation.runners.pilot_latex --placeholder paper/results_tables.tex
"""
import csv
import sys
from pathlib import Path

TBD = r'\tbd'


def cell(row, metric, digits=2, sd=True, scale=1.0):
    if row is None or row.get(metric+'_mean') in (None, ''):
        return TBD
    value = float(row[metric+'_mean']) * scale
    text = f'{value:.{digits}f}'
    if sd and row.get(metric+'_sd') not in (None, ''):
        text += r'$\pm$' + f'{float(row[metric+"_sd"]) * scale:.{digits}f}'
    return text


def counts(row):
    if row is None:
        return ''
    return f'{row["completed"]}/{row["scheduled"]}'


def tables(summary):
    find = lambda e, m, v: next((r for r in summary if r['experiment'] == e and r['evidence_mode'] == m and r['variant'] == v), None)
    out = [r'\begin{table}[t]', r'\centering\footnotesize',
           r'\caption{E1 evidence-format ablation (mean $\pm$ SD over repetitions; automatic judge, not human review). '
           r'Acc.\ = partial-credit accuracy; ALR = attribute leakage rate; Faith.\ = citation faithfulness; n = completed/scheduled.}',
           r'\label{tab:e1}', r'\setlength{\tabcolsep}{3pt}', r'\begin{tabular}{@{}llccccc@{}}', r'\toprule',
           r'Evidence & Fmt & Acc. & ALR $\downarrow$ & Faith. & Tokens & n \\', r'\midrule']
    for mode, label in (('gold', 'Gold'), ('retrieved', 'Retrieved')):
        for i, v in enumerate('ABCDE'):
            r = find('E1', mode, v)
            first = (r'\multirow{5}{*}{' + label + '}') if i == 0 else ''
            out.append(f'{first} & {v} & {cell(r,"partial_credit")} & {cell(r,"attribute_leakage_rate")} & '
                       f'{cell(r,"citation_faithfulness")} & {cell(r,"input_tokens",0,False)} & {counts(r)} \\\\')
        out.append(r'\midrule' if mode == 'gold' else r'\bottomrule')
    out += [r'\end{tabular}', r'\end{table}', '']
    out += [r'\begin{table}[t]', r'\centering\footnotesize',
            r'\caption{E2 graph-expansion ablation (top-3 retrieved seeds, 6{,}000-token ceiling; automatic judge).}',
            r'\label{tab:e2}', r'\setlength{\tabcolsep}{3pt}', r'\begin{tabular}{@{}lcccccc@{}}', r'\toprule',
            r'Mode & +Nodes & P@10 & Req.\ R & Acc. & ALR $\downarrow$ & Graph ms \\', r'\midrule']
    for v, label in (('A', 'A none'), ('B', 'B prev/next'), ('C', 'C structural'), ('D', 'D scope-aware')):
        r = find('E2', 'retrieved', v)
        out.append(f'{label} & {cell(r,"added_nodes",1,False)} & {cell(r,"evidence_precision_at_k",2,False)} & '
                   f'{cell(r,"required_evidence_recall",2,False)} & {cell(r,"partial_credit")} & '
                   f'{cell(r,"attribute_leakage_rate")} & {cell(r,"graph_latency_ms",0,False)} \\\\')
    out += [r'\bottomrule', r'\end{tabular}', r'\end{table}', '']
    out += [r'\begin{table}[t]', r'\centering\footnotesize',
            r'\caption{E4 visual-input comparison (gold evidence, table/figure questions; automatic judge). GPU memory is not '
            r'reported: inference ran on a remote server without memory telemetry.}',
            r'\label{tab:e4}', r'\setlength{\tabcolsep}{3pt}', r'\begin{tabular}{@{}lcccc@{}}', r'\toprule',
            r'Input & Acc. & Visual tok. & Prompt tok. & Latency (s) \\', r'\midrule']
    for v, label in (('F', 'Full-page VLM'), ('K', 'Crop VLM'), ('O', 'OCR only'), ('S', 'OCR + caption pods')):
        r = find('E4', 'gold', v)
        out.append(f'{label} & {cell(r,"partial_credit")} & {cell(r,"visual_tokens",0,False)} & '
                   f'{cell(r,"input_tokens",0,False)} & {cell(r,"generation_http_ms",1,False,0.001)} \\\\')
    out += [r'\bottomrule', r'\end{tabular}', r'\end{table}', '']
    return '\n'.join(out)


def main():
    if sys.argv[1] == '--placeholder':
        summary, target = [], sys.argv[2]
    else:
        with (Path(sys.argv[1])/'summary.csv').open(encoding='utf-8-sig') as stream:
            summary = list(csv.DictReader(stream))
        target = sys.argv[2]
    Path(target).write_text('% Generated by evaluation.runners.pilot_latex; do not edit by hand.\n' + tables(summary), encoding='utf-8')
    print('wrote', target)


if __name__ == '__main__':
    main()
